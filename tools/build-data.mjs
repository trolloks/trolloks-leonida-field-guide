// Builds app/data/trophies.json (the gate's file) and app/data/trophies.js (the same data as a classic script, so
// index.html also opens from file:// with the network off, where a module or fetch would be refused by Chrome).
// Official names, descriptions and grades are copied from source/official-trophies.json; everything else is ours.
// Run: node tools/build-data.mjs   (from the repository root). Fails loudly on any mismatch.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { NOTES, SOURCES, STAGES } from './notes.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const official = JSON.parse(readFileSync(root + 'source/official-trophies.json', 'utf8'));

const KINDS = ['story', 'collectibles', 'activities', 'meta'];
const byId = new Map(NOTES.map((n) => [n.id, n]));
if (byId.size !== NOTES.length) throw new Error('duplicate note id');

const trophies = official.trophies.map((o) => {
  const n = byId.get(o.id);
  if (!n) throw new Error(`no note for trophy ${o.id}`);
  if (!KINDS.includes(n.kind)) throw new Error(`bad kind for ${o.id}`);
  const stage = STAGES.find((s) => s.ids.includes(o.id));
  if (!stage) throw new Error(`trophy ${o.id} is in no roadmap stage`);
  return {
    id: o.id,
    name: o.name,
    description: o.description,
    grade: o.grade,
    kind: n.kind,
    missable: n.missable === true,
    missableBasis: n.missable === true ? n.missableBasis : null,
    count: n.count === null || n.count === undefined ? null : { target: n.count, source: n.countSource },
    stage: stage.id,
    sources: n.sources,
    guide: n.guide,
  };
});

const data = {
  game: official.game,
  platform: official.platform,
  list: official.list,
  notice: 'Unofficial fan tracker. Not made by or affiliated with Rockstar Games, Take-Two or PlayStation.',
  sources: SOURCES,
  stages: STAGES.map((s) => ({ id: s.id, title: s.title, summary: s.summary, ids: s.ids })),
  trophies,
};

const json = JSON.stringify(data, null, 2) + '\n';
writeFileSync(root + 'app/data/trophies.json', json);
writeFileSync(root + 'app/data/trophies.js', `// Generated by tools/build-data.mjs from app/data/trophies.json. Do not edit by hand.\nwindow.GTA6_TROPHY_DATA = ${JSON.stringify(data)};\n`);
console.log(`wrote ${trophies.length} trophies, ${STAGES.length} stages`);
